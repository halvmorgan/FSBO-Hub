/**
 * Helper to normalize any input state (name or 2-letter abbreviation) to StateDisclosureInfo
 */
export function getStateDisclosureInfo(stateInput?: string | null): StateDisclosureInfo {
  if (!stateInput || typeof stateInput !== 'string') {
    return STATE_DISCLOSURES.MI; // Safe fallback
  }

  const cleaned = stateInput.trim().toUpperCase();

  // Direct code match (e.g. "MI", "CA", "TX")
  if (STATE_DISCLOSURES[cleaned]) {
    return STATE_DISCLOSURES[cleaned];
  }

  // Name match (e.g. "Michigan", "California")
  const foundState = US_STATES.find(
    (s) => s.name.toLowerCase() === stateInput.trim().toLowerCase()
  );
  if (foundState && STATE_DISCLOSURES[foundState.code]) {
    return STATE_DISCLOSURES[foundState.code];
  }

  // Fallback to Michigan
  return STATE_DISCLOSURES.MI;
}

/**
 * Automatically extracts a US state code or name from a raw address string.
 */
export function detectStateFromAddress(addressString: string): string | null {
  if (!addressString) return null;

  // 1. Look for 2-letter state code before a 5-digit zip (e.g. "TX 75001" or "MI, 48306")
  const zipMatch = addressString.match(/\b([A-Za-z]{2})[,.\s]+(\d{5})\b/);
  if (zipMatch && zipMatch[1]) {
    const code = zipMatch[1].toUpperCase();
    if (STATE_DISCLOSURES[code]) {
      return STATE_DISCLOSURES[code].stateName;
    }
  }

  // 2. Look for full state names in the string
  for (const s of US_STATES) {
    const regex = new RegExp(`\\b${s.name}\\b`, 'i');
    if (regex.test(addressString)) {
      return s.name;
    }
  }

  // 3. Look for standalone state abbreviation at the end or surrounded by commas
  for (const s of US_STATES) {
    const regex = new RegExp(`[,\\s]${s.code}(?:[,\\s]|$)`, 'i');
    if (regex.test(addressString)) {
      return s.name;
    }
  }

  return null;
}
